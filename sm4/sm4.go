// BlockSize SM4 分组字节长度。
const BlockSize = 16

// KeySize SM4 密钥字节长度。
const KeySize = 16

// KeySizeError 表示密钥长度不合法。
type KeySizeError int

func (k KeySizeError) Error() string {
	return fmt.Sprintf("sm4: 密钥长度不合法，应为 %d 字节，实际 %d 字节", KeySize, int(k))
}

