// Cipher 是一个已完成密钥扩展的 SM4 实例，实现 cipher.Block 接口。
type Cipher struct {
	rk [32]uint32 // 轮密钥 rk[0..31]
}

// NewCipher 创建 SM4 分组密码实例，key 必须为 16 字节。
func NewCipher(key []byte) (cipher.Block, error) {
	if len(key) != KeySize {
		return nil, KeySizeError(len(key))
	}
	c := new(Cipher)
	c.expandKey(key)
	return c, nil
}

// BlockSize 返回分组字节长度。
func (c *Cipher) BlockSize() int { return BlockSize }

func rotl(x uint32, n uint32) uint32 {
	n &= 31
	return x<<n | x>>(32-n)
}

// tau 非线性变换 τ：对 32 位字的 4 个字节并行做 S 盒代换（GB/T 32907-2016 6.2）。
func tau(a uint32) uint32 {
	return uint32(sbox[a>>24])<<24 |
		uint32(sbox[a>>16&0xff])<<16 |
		uint32(sbox[a>>8&0xff])<<8 |
		uint32(sbox[a&0xff])
}

// tSub 合成置换 T = L(τ(.))，用于轮函数（GB/T 32907-2016 6.2）。
func tSub(a uint32) uint32 {
	b := tau(a)
	return b ^ rotl(b, 2) ^ rotl(b, 10) ^ rotl(b, 18) ^ rotl(b, 24)
}

// tSubKey 密钥扩展用的合成置换 T' = L'(τ(.))（GB/T 32907-2016 7.3）。
func tSubKey(a uint32) uint32 {
	b := tau(a)
	return b ^ rotl(b, 13) ^ rotl(b, 23)
}

// expandKey 由加密密钥生成 32 个轮密钥（GB/T 32907-2016 7.3）。
func (c *Cipher) expandKey(key []byte) {
	var k [4]uint32
	for i := 0; i < 4; i++ {
		k[i] = binary.BigEndian.Uint32(key[i*4:]) ^ fk[i]
	}
	for i := 0; i < 32; i++ {
		rk := k[0] ^ tSubKey(k[1]^k[2]^k[3]^ck[i])
		c.rk[i] = rk
		k[0], k[1], k[2], k[3] = k[1], k[2], k[3], rk
	}
}

// crypt 执行 32 轮迭代与反序变换。encrypt 为 true 时按 rk[0..31] 顺序取轮密钥，
// 否则按 rk[31..0] 逆序——SM4 的解密与加密结构相同，仅轮密钥使用顺序相反。
func (c *Cipher) crypt(dst, src []byte, encrypt bool) {
	var x [4]uint32
	for i := 0; i < 4; i++ {
		x[i] = binary.BigEndian.Uint32(src[i*4:])
	}
	for i := 0; i < 32; i++ {
		rk := c.rk[i]
		if !encrypt {
			rk = c.rk[31-i]
		}
		// X[i+4] = X[i] ^ T(X[i+1] ^ X[i+2] ^ X[i+3] ^ rk[i])
		t := x[0] ^ tSub(x[1]^x[2]^x[3]^rk)
		x[0], x[1], x[2], x[3] = x[1], x[2], x[3], t
	}
	// 反序变换 R：(X32, X33, X34, X35) -> (X35, X34, X33, X32)
	for i := 0; i < 4; i++ {
		binary.BigEndian.PutUint32(dst[i*4:], x[3-i])
	}
}

// Encrypt 加密 src 中的一个分组并写入 dst。
func (c *Cipher) Encrypt(dst, src []byte) {
	if len(src) < BlockSize {
		panic("sm4: 输入分组长度不足")
	}
	if len(dst) < BlockSize {
		panic("sm4: 输出分组长度不足")
	}
	c.crypt(dst, src, true)
}

// Decrypt 解密 src 中的一个分组并写入 dst。
func (c *Cipher) Decrypt(dst, src []byte) {
	if len(src) < BlockSize {
		panic("sm4: 输入分组长度不足")
	}
	if len(dst) < BlockSize {
		panic("sm4: 输出分组长度不足")
	}
	c.crypt(dst, src, false)
}
